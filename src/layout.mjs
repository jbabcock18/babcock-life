export const icon = (name, className = 'icon') =>
  `<svg class="${className}" aria-hidden="true" focusable="false"><use href="#${name}"/></svg>`;

// Set the theme before first paint so a saved choice never flashes the other one.
const THEME_SCRIPT = `(function(){var d=document.documentElement;d.className=d.className.replace('no-js','js');try{var t=localStorage.getItem('theme');if(t==='light'||t==='dark')d.dataset.theme=t}catch(e){}})()`;

export function renderPage({ model, version, page, section, title, description, kind, body, scripts = [] }) {
  const to = linker(page);
  const { site } = model;
  const fullTitle = title ? `${title} | ${site.name}` : site.name;
  const asset = (file) => `${to(file)}?v=${version}`;

  const nav = site.nav
    .map((item) => {
      const active = item.label === section;
      return `<a class="nav__link${active ? ' is-active' : ''}" href="${to(item.url)}"${active ? ' aria-current="page"' : ''}>${esc(item.label)}</a>`;
    })
    .join('\n          ');

  return `<!DOCTYPE html>
<!-- Generated by build.mjs. Edit the files in content/ or src/, then run: node build.mjs -->
<html lang="en" class="no-js" data-root="${to.prefix}" data-page="${kind}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${esc(fullTitle)}</title>
    <meta name="description" content="${esc(description)}" />
    <meta property="og:title" content="${esc(title || site.name)}" />
    <meta property="og:description" content="${esc(description)}" />
    <meta property="og:type" content="website" />
    <meta name="color-scheme" content="light dark" />
    <meta name="theme-color" content="#fbfcfe" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#071030" media="(prefers-color-scheme: dark)" />
    <link rel="icon" type="image/svg+xml" href="${to('favicon.svg')}" />
    <link rel="preload" href="${to('assets/fonts/bodoni-moda-latin-italic.woff2')}" as="font" type="font/woff2" crossorigin />
    <link rel="preload" href="${to('assets/fonts/source-serif-4-latin-roman.woff2')}" as="font" type="font/woff2" crossorigin />
    <link rel="stylesheet" href="${asset('assets/site.css')}" />
    <script>${THEME_SCRIPT}</script>
    <script defer src="${asset('assets/site.js')}"></script>
${scripts.map((file) => `    <script defer src="${asset(file)}"></script>`).join('\n')}
  </head>
  <body>
    ${SPRITE}
    <a class="skip-link" href="#main">Skip to content</a>

    <header class="masthead">
      <div class="wrap masthead__bar">
        <a class="brand" href="${to('index.html')}" aria-label="${esc(site.name)}, home">
          ${icon('rosette', 'brand__mark')}
          <span class="brand__name">${esc(site.name)}</span>
        </a>
        <nav class="nav" aria-label="Primary">
          ${nav}
        </nav>
        <div class="masthead__tools">
          <button class="tool tool--search" type="button" data-palette-open aria-haspopup="dialog" aria-keyshortcuts="Meta+K Control+K">
            ${icon('search')}<span class="tool__text">Search</span><kbd class="tool__key" data-shortcut>⌘K</kbd>
          </button>
          <button class="tool tool--theme" type="button" data-theme-toggle aria-label="Switch colour theme">
            ${icon('half')}
          </button>
        </div>
      </div>
    </header>

    <main id="main" class="page page--${kind}">
${body}
    </main>

    ${renderFooter(model, to)}
  </body>
</html>
`;
}

function renderFooter(model, to) {
  const { site, lastSeen } = model;
  const links = [
    ...site.links.map(
      (link) => `<li><a href="${esc(link.url)}" target="_blank" rel="noreferrer">${esc(link.label)}${icon('arrow-out', 'icon icon--inline')}</a></li>`,
    ),
    `<li><a href="${to('colophon.html')}">Colophon</a></li>`,
  ].join('\n            ');

  const fix = lastSeen
    ? `<div class="footer__fix" title="From the most recent geotagged photo on this site">
          <p class="label">Last seen</p>
          <p>${esc(lastSeen.place.name)}, ${esc(lastSeen.place.area)}<br />${esc(formatDate(lastSeen.taken))}<br />${formatCoordinate(lastSeen.gps.lat, 'lat', 2)} ${formatCoordinate(lastSeen.gps.lon, 'lon', 2)}</p>
        </div>`
    : '';

  return `<footer class="footer">
      <div class="wrap">
        <div class="scale-rule" aria-hidden="true"></div>
        <div class="footer__grid">
          <div class="footer__brand">
            ${icon('rosette', 'footer__mark')}
            <p class="footer__name">${esc(site.name)}</p>
            <p class="footer__tag">${esc(site.tagline)}</p>
          </div>
          <nav class="footer__nav" aria-label="Footer">
            <p class="label">Pages</p>
            <ul>
              ${site.nav.map((item) => `<li><a href="${to(item.url)}">${esc(item.label)}</a></li>`).join('\n              ')}
            </ul>
          </nav>
          <div class="footer__nav">
            <p class="label">Elsewhere</p>
            <ul>
            ${links}
            </ul>
          </div>
          ${fix}
        </div>
        <p class="footer__fine">Designed and built by Fable 5.2 in Cursor. <a href="${to('colophon.html')}">How it was made</a></p>
      </div>
    </footer>`;
}

/** A responsive image with the photo's average colour behind it while it loads. */
export function image(photo, to, { sizes = '100vw', eager = false, className = '' } = {}) {
  return `<img${className ? ` class="${className}"` : ''} src="${to(photo.small)}" srcset="${to(photo.small)} 480w, ${to(photo.full)} ${photo.width}w" sizes="${sizes}" width="${photo.width}" height="${photo.height}" alt="${esc(photo.alt)}" ${eager ? 'fetchpriority="high"' : 'loading="lazy"'} decoding="async" style="background-color:${photo.color}${photo.focus ? `;object-position:${photo.focus}` : ''}" />`;
}

/** An image that opens in the lightbox (or, without JavaScript, as a plain file). */
export function zoomable(photo, to, { caption, group = '', ...options } = {}) {
  return `<a class="zoom" href="${to(photo.full)}" data-zoom${group ? ` data-zoom-group="${esc(group)}"` : ''} data-width="${photo.width}" data-height="${photo.height}" data-caption="${esc(caption || '')}">${image(photo, to, options)}</a>`;
}

/** Top of an index or detail page. */
export function pageHead({ back, label, title, lede, wide = false }) {
  return `<header class="page-head${wide ? ' page-head--wide' : ''}">
          ${back ? `<a class="back" href="${back.href}">${icon('arrow', 'icon icon--back')}${esc(back.label)}</a>` : ''}
          ${label ? `<p class="label page-head__label">${label}</p>` : ''}
          <h1 class="page-head__title">${title}</h1>
          ${lede ? `<p class="page-head__lede">${lede}</p>` : ''}
        </header>`;
}

/** The dotted-leader list from the original site: title ........ detail */
export function leaders(items) {
  return `<ol class="leaders">
${items
  .map(
    (item) => `          <li>
            <a class="leaders__row" href="${item.href}">
              <span class="leaders__title">${item.title}</span>${item.sub ? `\n              <span class="leaders__sub">${item.sub}</span>` : ''}
              <span class="leaders__dots" aria-hidden="true"></span>
              <span class="leaders__meta">${item.meta}</span>
            </a>
          </li>`,
  )
  .join('\n')}
        </ol>`;
}
