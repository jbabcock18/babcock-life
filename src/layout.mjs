/** Relative link helper: pages live at different depths and the site must work from any folder. */
export function linker(page) {
  const depth = page.split('/').length - 1;
  const prefix = depth === 0 ? './' : '../'.repeat(depth);
  const to = (target) => prefix + target.split('/').map(encodeURIComponent).join('/').replace(/%23/g, '#');
  to.prefix = prefix;
  return to;
}

